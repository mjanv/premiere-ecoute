export const GLYPHS = Object.fromEntries(Object.entries(ROWS).map(([char, rows]) => [char, rows.split(" ")]));

const REPLACEMENTS = { "’": "'", "‘": "'", "“": '"', "”": '"', "–": "-", "—": "-", "…": "...", Œ: "OE", Æ: "AE", ẞ: "SS", "×": "X", "·": "." };

// Brings any text to what the font can draw: capitals without accents
export function clean(text) {
  // ≠ would lose its stroke with the accents
  return String(text ?? "").split("≠").map(plain).join("≠");
}

function plain(text) {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toUpperCase()
    .replace(/[’‘“”–—…ŒÆẞ×·]/g, (char) => REPLACEMENTS[char])
    .replace(/\s+/g, " ")
    .trim();
}

export const glyph = (char) => (char === " " ? null : GLYPHS[char] || GLYPHS["\u0000"]);
